export type PaletteColorName = keyof typeof _PALETTE;
export type PaletteShade = keyof (typeof _PALETTE)[PaletteColorName];
type ColorScale = Record<PaletteShade, string>;

function hexToHsl(hex: string): { h: number; s: number; l: number } {
  let r = 0,
    g = 0,
    b = 0;
  hex = hex.replace('#', '');
  if (hex.length === 3) {
    r = parseInt(hex[0] + hex[0], 16) / 255;
    g = parseInt(hex[1] + hex[1], 16) / 255;
    b = parseInt(hex[2] + hex[2], 16) / 255;
  } else if (hex.length === 6) {
    r = parseInt(hex.substring(0, 2), 16) / 255;
    g = parseInt(hex.substring(2, 4), 16) / 255;
    b = parseInt(hex.substring(4, 6), 16) / 255;
  }
  const max = Math.max(r, g, b),
    min = Math.min(r, g, b);
  let h = 0,
    s = 0,
    l = (max + min) / 2;

  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r:
        h = (g - b) / d + (g < b ? 6 : 0);
        break;
      case g:
        h = (b - r) / d + 2;
        break;
      case b:
        h = (r - g) / d + 4;
        break;
    }
    h /= 6;
  }
  return { h: h * 360, s: s * 100, l: l * 100 };
}

function hslToHex(h: number, s: number, l: number): string {
  s /= 100;
  l /= 100;
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => {
    const k = (n + h / 30) % 12;
    const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(255 * color)
      .toString(16)
      .padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

export function generateScaleFrom500(baseHex: string): ColorScale {
  const { h, s, l: baseL } = hexToHsl(baseHex);

  // Mapeo de curvas de luminosidad (L) relativas al nivel 500
  // Diseñadas para emular la progresión perceptual de Tailwind / PrimeNG
  const lightnessMap: Record<keyof ColorScale, number> = {
    50: Math.min(98, baseL + (100 - baseL) * 0.92),
    100: Math.min(94, baseL + (100 - baseL) * 0.8),
    200: Math.min(86, baseL + (100 - baseL) * 0.6),
    300: Math.min(76, baseL + (100 - baseL) * 0.4),
    400: Math.min(64, baseL + (100 - baseL) * 0.2),
    500: baseL, // Color exacto seleccionado
    600: baseL * 0.85,
    700: baseL * 0.7,
    800: baseL * 0.55,
    900: baseL * 0.4,
    950: baseL * 0.22,
  };

  // Ajuste sutil de saturación en los extremos para evitar tonos apagados
  const getSaturation = (step: string): number => {
    const stepNum = parseInt(step, 10);
    if (stepNum <= 100) return Math.min(100, s * 0.85); // Suavizar tonos claros
    if (stepNum >= 800) return Math.min(100, s * 1.15); // Compensar pérdida de color en oscuridad
    return s;
  };

  const scale: Partial<ColorScale> = {};
  for (const [step, targetL] of Object.entries(lightnessMap)) {
    if (step === '500') {
      scale['500'] = baseHex.toLowerCase();
    } else {
      scale[Number(step) as keyof ColorScale] = hslToHex(h, getSaturation(step), targetL);
    }
  }

  return scale as ColorScale;
}

export function resolvePaletteScale(inputColor: string) {
  const normalizedInput = inputColor?.toLowerCase().trim();

  for (const [name, scale] of Object.entries(_PALETTE)) {
    if (scale[500].toLowerCase() === normalizedInput) return scale;
  }

  return generateScaleFrom500(normalizedInput);
}
